#!/usr/bin/env python3
"""Generate market worlds that differ only in the size of the action grid.

The economics are identical across variants: quote a two-sided market, get
filled by a customer with a private value, carry inventory, pay for risk. The
only thing that changes is how finely the desk can choose its (width, skew)
posture. That makes action count the single free variable.

  market_A4   2 widths x 2 skews
  market_A8   2 widths x 4 skews
  market_A16  4 widths x 4 skews
"""
from pathlib import Path

ROOT = Path("/home/user/workspace/repo")
OUT = ROOT / ".hunch-cache"

TEMPLATE = """// Market maker with a {nw} x {ns} quote grid ({na} actions).
// Generated by benchmarks/make_market_variants.py -- same economics as
// worlds/market.hunch, only the action resolution differs.

world Market{na}

horizon 48

state {{
  mid: float = 100.0;
  inv: float = 0.0;
  cash: float = 0.0;
  vol: float = 1.0;
}}

step {{
  let act = hunch mm([
    inv / 5.0,
    (mid - 100.0) / 8.0,
    vol,
    step_count() / 48.0
  ], {na});

  // action -> (width index, skew index)
  let wi = floor(act / {ns}.0);
  let si = act - wi * {ns}.0;

  let width = {w0} + wi * {wdw};
  let skew = (si - {smid}) * {ss};

  let bid = mid - width - skew;
  let ask = mid + width - skew;

  let eq0 = cash + inv * mid;

  let u = rand() * 2.0 - 1.0;
  if u > width - skew {{
    inv = inv - 1.0;
    cash = cash + ask;
  }} else {{
    if u < -width - skew {{
      inv = inv + 1.0;
      cash = cash - bid;
    }}
  }}

  if rand() < 0.07 {{
    if vol < 2.0 {{
      vol = 2.2;
    }} else {{
      vol = 0.8;
    }}
  }}
  mid = mid + (rand() - 0.5) * vol * 0.35;

  let eq1 = cash + inv * mid;
  reward((eq1 - eq0) / 4.0 - 0.002 * inv * inv);
}}
"""


def make(nw: int, ns: int) -> str:
    na = nw * ns
    # half-spread from 0.5 up to ~2.0 regardless of grid resolution
    w0 = 0.5
    wdw = 1.5 / max(1, nw - 1) if nw > 1 else 0.0
    # skew from -0.24 to +0.24
    ss = 0.48 / max(1, ns - 1) if ns > 1 else 0.0
    smid = (ns - 1) / 2.0
    return TEMPLATE.format(nw=nw, ns=ns, na=na, w0=w0, wdw=wdw, ss=ss, smid=smid)


def main() -> int:
    OUT.mkdir(exist_ok=True)
    for nw, ns in [(2, 2), (2, 4), (4, 4), (4, 8)]:
        na = nw * ns
        path = OUT / f"market_A{na}.hunch"
        path.write_text(make(nw, ns))
        print(f"wrote {path} ({na} actions, {nw}x{ns} grid)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
